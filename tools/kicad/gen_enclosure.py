"""Write the OpenSCAD enclosure for the controller from design.py, then render STLs and previews.

The .scad is plain and parametric so it can be tweaked by hand: every cut-out is a named
list near the top of the file.
"""
import os
import subprocess
import sys
import design

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.normpath(os.path.join(HERE, "..", "..", "hardware", "controller", "enclosure"))


def notches():
    """(name, wall, from, to, window_bottom, window_top) in board mm. window = height above the PCB top
    that stays open once the lid's tab drops into the notch."""
    return [
        # top edge (head end)
        ("head pigtails J9-J11", "top", 24.5, 58.0, 0, 7),
        ("speaker J15", "top", 70.5, 80.5, 0, 7),
        ("Qwiic J14", "top", 83.0, 92.5, 0, 7),
        # left arm
        ("J6 shoulder", "left", 34.0, 44.5, 0, 7),
        ("J7 elbow", "left", 46.0, 58.0, 0, 7),
        ("J8 switch", "left", 59.5, 74.0, 0, 7),
        # right arm
        ("J3 shoulder", "right", 34.0, 44.5, 0, 7),
        ("J4 elbow", "right", 46.0, 58.0, 0, 7),
        ("J5 switch", "right", 59.5, 74.0, 0, 7),
        # bottom edge
        ("J1 barrel jack", "bottom", 6.4, 18.4, 0, 13.0),
        ("ESP32 USB-C", "bottom", 37.0, 63.0, 9.5, 19.0),
        ("J12 trigger", "bottom", 65.4, 73.8, 0, 6.0),
        ("J13 PIR", "bottom", 75.0, 88.5, 0, 7),
    ]


SCAD = r'''// Freddy controller rev A enclosure. Generated by tools/kicad/gen_enclosure.py from design.py.
// Units: mm. Board coordinates: origin at the PCB's top-left corner, head end up (+y = toward the PSU end).
// Print base and lid separately (render with -D part="base" / "lid"). PETG or PA12 recommended.

part = "assembly";        // "base", "lid" or "assembly"

pcb_w = %(W)s; pcb_h = %(H)s; pcb_t = 1.6;
gap = 0.75;               // clearance around the PCB
wall = 2.2; floor_t = 2.0; lid_t = 2.0;
standoff_h = 6.0;         // PCB bottom above the floor (through-hole pins stick out ~2.5mm)
clear_above = 26.0;       // tallest part above the PCB top: the upright S7V7F5 (~23.5mm), C1 (10x16 or 10x20)
corner_r = 4.0;

holes = %(HOLES)s;        // PCB mounting holes (M3)
// notches: [name, wall, from, to, window_bottom, window_top]  (window heights above the PCB top)
notches = %(NOTCHES)s;
// vents in the lid over the warm parts: [x0, y0, x1, y1] board coordinates
vents = [[17, 40, 33, 58], [67, 55, 83, 73], [12, 13, 32, 34]];

in_w = pcb_w + 2*gap; in_h = pcb_h + 2*gap;
out_w = in_w + 2*wall; out_h = in_h + 2*wall;
pcb_top = floor_t + standoff_h + pcb_t;
box_h = pcb_top + clear_above;          // base wall height (lid sits on top)

function bx(x) = wall + gap + x;        // board x -> enclosure x
function by(y) = out_h - (wall + gap + y);   // board y -> enclosure y (board y grows downward)

module rounded(w, h, z, r) {
    hull() for (x = [r, w - r], y = [r, h - r]) translate([x, y, 0]) cylinder(r = r, h = z, $fn = 40);
}

module notch_cut(n, extra = 0) {
    wl = n[1]; a = n[2]; b = n[3];
    z0 = pcb_top + n[4] - extra; z1 = box_h + 1;
    if (wl == "top")    translate([bx(a), out_h - wall - 1, z0]) cube([b - a, wall + 2, z1 - z0]);
    if (wl == "bottom") translate([bx(a), -1, z0]) cube([b - a, wall + 2, z1 - z0]);
    if (wl == "left")   translate([-1, by(b), z0]) cube([wall + 2, b - a, z1 - z0]);
    if (wl == "right")  translate([out_w - wall - 1, by(b), z0]) cube([wall + 2, b - a, z1 - z0]);
}

module base() {
    difference() {
        union() {
            difference() {
                rounded(out_w, out_h, box_h, corner_r);
                translate([wall, wall, floor_t]) rounded(in_w, in_h, box_h, corner_r - wall);
            }
            // standoffs
            for (h = holes) translate([bx(h[0]), by(h[1]), 0]) cylinder(d = 7, h = floor_t + standoff_h, $fn = 40);
            // mounting ears (screw the box inside Freddy)
            for (y = [out_h * 0.3, out_h * 0.7], s = [0, 1])
                translate([s ? out_w : 0, y, 0]) mirror([s, 0, 0]) ear();
        }
        for (n = notches) notch_cut(n);
        // M3 self-tapping screws into the standoffs (2.6mm pilot)
        for (h = holes) translate([bx(h[0]), by(h[1]), floor_t]) cylinder(d = 2.6, h = standoff_h + 1, $fn = 24);
        // labels on the floor's underside
        translate([out_w / 2, out_h / 2, 0.6]) rotate([180, 0, 0])
            linear_extrude(1) text("FREDDY rev A", size = 7, halign = "center", valign = "center");
    }
}

module ear() {
    difference() {
        hull() {
            translate([-9, -6, 0]) cube([9, 12, 3]);
        }
        translate([-4.5, 0, -1]) cylinder(d = 3.5, h = 5, $fn = 24);
    }
}

module lid() {
    lip = 3.0; lip_t = 1.4; fit = 0.25;
    difference() {
        union() {
            rounded(out_w, out_h, lid_t, corner_r);
            // locating lip just inside the walls
            translate([0, 0, -lip]) difference() {
                translate([wall + fit, wall + fit, 0]) rounded(in_w - 2*fit, in_h - 2*fit, lip, corner_r - wall);
                translate([wall + fit + lip_t, wall + fit + lip_t, -1]) rounded(in_w - 2*fit - 2*lip_t, in_h - 2*fit - 2*lip_t, lip + 2, 1);
            }
            // tabs that drop into each notch, leaving the cable window open
            for (n = notches) tab(n);
        }
        for (v = vents) for (x = [v[0] + 1.5 : 3.2 : v[2] - 1.5])
            translate([bx(x) - 0.8, by(v[3]), -lip - 1]) cube([1.6, v[3] - v[1], lid_t + lip + 2]);
        // labels
        translate([out_w / 2, out_h - 8, lid_t - 0.6]) linear_extrude(1) text("HEAD", size = 5, halign = "center");
        translate([8, out_h / 2, lid_t - 0.6]) rotate(90) linear_extrude(1) text("LEFT ARM", size = 4.5, halign = "center");
        translate([out_w - 8, out_h / 2, lid_t - 0.6]) rotate(-90) linear_extrude(1) text("RIGHT ARM", size = 4.5, halign = "center");
        translate([bx(12.4), 6, lid_t - 0.6]) linear_extrude(1) text("7.2V", size = 4, halign = "center");
        translate([bx(50), 6, lid_t - 0.6]) linear_extrude(1) text("USB", size = 4, halign = "center");
        translate([bx(69.6), 6, lid_t - 0.6]) linear_extrude(1) text("TRIG", size = 3.5, halign = "center");
        translate([bx(81.5), 6, lid_t - 0.6]) linear_extrude(1) text("PIR", size = 3.5, halign = "center");
    }
}

module tab(n) {
    t = 0.3;  // fit
    wl = n[1]; a = n[2] + t; b = n[3] - t;
    depth = box_h - (pcb_top + n[5]);           // from the wall top down to the window top
    if (depth > 0) {
        if (wl == "top")    translate([bx(a), out_h - wall, -depth]) cube([b - a, wall, depth]);
        if (wl == "bottom") translate([bx(a), 0, -depth]) cube([b - a, wall, depth]);
        if (wl == "left")   translate([0, by(b), -depth]) cube([wall, b - a, depth]);
        if (wl == "right")  translate([out_w - wall, by(b), -depth]) cube([wall, b - a, depth]);
    }
}

module pcb_ghost() {
    color("green", 0.6) translate([bx(0), by(pcb_h), floor_t + standoff_h]) cube([pcb_w, pcb_h, pcb_t]);
}

if (part == "base") base();
else if (part == "lid") translate([0, 0, lid_t]) rotate([180, 0, 0]) translate([0, -out_h, 0]) lid();
else {
    color("#3b3b3b") base();
    pcb_ghost();
    color("#5a5a5a", 0.9) translate([0, 0, box_h + 12]) lid();
}
'''


def scad_list(items):
    def fmt(v):
        return '"%s"' % v if isinstance(v, str) else ("%g" % v)
    return "[" + ", ".join("[" + ", ".join(fmt(v) for v in it) + "]" for it in items) + "]"


def main(render=True):
    os.makedirs(OUT, exist_ok=True)
    scad = SCAD % {"W": design.BOARD_W, "H": design.BOARD_H,
                   "HOLES": scad_list(design.MOUNT_HOLES), "NOTCHES": scad_list(notches())}
    path = os.path.join(OUT, "freddy_enclosure.scad")
    with open(path, "w") as f:
        f.write(scad)
    print("wrote", path)
    if not render:
        return
    for part in ("base", "lid"):
        stl = os.path.join(OUT, f"freddy_enclosure_{part}.stl")
        subprocess.run(["openscad", "-o", stl, "-D", f'part="{part}"', path], check=True,
                       stdout=subprocess.DEVNULL, stderr=subprocess.PIPE)
        print("wrote", stl)


if __name__ == "__main__":
    main(render="--no-render" not in sys.argv)
