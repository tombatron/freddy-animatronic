#!/usr/bin/env python3
"""Embed Hotwired Turbo in the ESP32 firmware as a gzipped byte array.

The page then works with no internet access (e.g. when Freddy runs his own
WiFi access point). Regenerate when upgrading Turbo:

    npm pack @hotwired/turbo@8.0.23 && tar xzf hotwired-turbo-8.0.23.tgz
    npx terser package/dist/turbo.es2017-umd.js -c -m -o turbo.min.js
    python3 tools/make_turbo_header.py turbo.min.js 8.0.23

Turbo is MIT licensed, (c) 37signals LLC. https://turbo.hotwired.dev
"""
import gzip
import os
import sys

src, version = sys.argv[1], sys.argv[2]
data = gzip.compress(open(src, "rb").read(), compresslevel=9, mtime=0)
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "firmware", "freddy_web", "turbo_js.h")
with open(out, "w") as f:
    f.write(f"// Hotwired Turbo {version} (MIT, (c) 37signals LLC), minified and gzipped.\n")
    f.write("// Generated by tools/make_turbo_header.py. Do not edit.\n#pragma once\n#include <stdint.h>\n#include <stddef.h>\n\n")
    f.write(f"const size_t TURBO_JS_GZ_LEN = {len(data)};\nconst uint8_t TURBO_JS_GZ[] = {{\n")
    for i in range(0, len(data), 20):
        f.write("  " + ", ".join(f"0x{b:02x}" for b in data[i:i + 20]) + ",\n")
    f.write("};\n")
print(f"wrote {out}: {len(data)} bytes gzipped")
